CREATE TYPE ULOGA_TIP AS ENUM ('KLIJENT', 'RADNIK', 'ADMIN');

CREATE TABLE KORISNIK(
    KORISNIK_ID INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT KORISNIK_PK PRIMARY KEY,
	EMAIL VARCHAR(100) NOT NULL CONSTRAINT KORISNIK_EMAIL_UQ UNIQUE,
	LOZINKA VARCHAR(255) NOT NULL,
	ULOGA ULOGA_TIP NOT NULL
);

CREATE TABLE KLIJENT(
    KORISNIK_ID INTEGER CONSTRAINT KLIJENT_PK PRIMARY KEY,
    OIB CHAR(11) NOT NULL CONSTRAINT KLIJENT_OIB_UQ UNIQUE,
	IME VARCHAR(50) NOT NULL,
	PREZIME VARCHAR(50) NOT NULL,
	BROJ_TELEFONA VARCHAR(50) NOT NULL,
	CONSTRAINT KLIJENT_KORISNIK_FK FOREIGN KEY (KORISNIK_ID) REFERENCES
	KORISNIK (KORISNIK_ID) ON DELETE CASCADE
);

CREATE TABLE RADNIK(
    KORISNIK_ID INTEGER CONSTRAINT RADNIK_PK PRIMARY KEY,
	IME VARCHAR(50) NOT NULL,
	PREZIME VARCHAR(50) NOT NULL,
	BROJ_TELEFONA VARCHAR(50) NOT NULL,
	PLACA NUMERIC(10, 2),
	CONSTRAINT RADNIK_KORISNIK_FK FOREIGN KEY (KORISNIK_ID) REFERENCES
	KORISNIK (KORISNIK_ID) ON DELETE CASCADE

);

CREATE TABLE USLUGA(
    USLUGA_ID INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT USLUGA_PK PRIMARY KEY,
	CIJENA INTEGER NOT NULL,
	TRAJANJE INTEGER NOT NULL

);

CREATE TABLE NOKTI (
	USLUGA_ID INTEGER NOT NULL CONSTRAINT NOKTI_FK_USLUGA
	REFERENCES USLUGA(USLUGA_ID),
	VRSTA_NOKTIJU VARCHAR(30) NOT NULL,
	CONSTRAINT NOKTI_PK PRIMARY KEY (USLUGA_ID)
);


CREATE TABLE DEPILACIJA_VOSKOM (
	USLUGA_ID INTEGER NOT NULL CONSTRAINT DEPILACIJA_VOSKOM_FK_USLUGA
	REFERENCES USLUGA(USLUGA_ID),
	PODRUCJE_DEPILACIJE VARCHAR(30) NOT NULL,
	CONSTRAINT DEPILACIJA_VOSKOM_PK PRIMARY KEY (USLUGA_ID)
);

CREATE TABLE TREPAVICE (
	USLUGA_ID INTEGER NOT NULL CONSTRAINT TREPAVICE_FK_USLUGA
	REFERENCES USLUGA(USLUGA_ID),
	VRSTA_TREPAVICA VARCHAR(30) NOT NULL,
	CONSTRAINT TREPAVICE_PK PRIMARY KEY (USLUGA_ID)
);

CREATE TABLE OBRVE (
	USLUGA_ID INTEGER NOT NULL CONSTRAINT OBRVE_FK_USLUGA
	REFERENCES USLUGA(USLUGA_ID),
	VRSTA_OBRVA VARCHAR(20) NOT NULL,
	CONSTRAINT OBRVE_PK PRIMARY KEY (USLUGA_ID)
);


CREATE TABLE SMINKANJE (
	USLUGA_ID INTEGER NOT NULL CONSTRAINT SMINKANJE_FK_USLUGA
	REFERENCES USLUGA(USLUGA_ID),
	VRSTA_SMINKE VARCHAR(30) NOT NULL,
	CONSTRAINT SMINKANJE_PK PRIMARY KEY (USLUGA_ID)
);

CREATE TABLE RADNIK_USLUGA (
	USLUGA_ID INTEGER NOT NULL CONSTRAINT RADNIK_USLUGA_FK_USLUGA
	REFERENCES USLUGA(USLUGA_ID),
	KORISNIK_ID INTEGER NOT NULL CONSTRAINT RADNIK_USLUGA_FK_RADNIK
	REFERENCES RADNIK(KORISNIK_ID),
	CONSTRAINT RADNIK_USLUGA_PK PRIMARY KEY (USLUGA_ID, KORISNIK_ID)
);

CREATE TYPE STATUS_REZERVACIJE AS ENUM ('AKTIVNA', 'OTKAZANA', 'POTVRDJENA', 'ISTEKLA');

CREATE TABLE RADNO_VRIJEME (
    RADNO_VRIJEME_ID INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT RADNO_VRIJEME_PK PRIMARY KEY,
    DAN_U_TJEDNU SMALLINT NOT NULL CHECK (DAN_U_TJEDNU BETWEEN 1 AND 7),
    VRIJEME_OD TIME NOT NULL,
    VRIJEME_DO TIME NOT NULL,
    CHECK (VRIJEME_OD < VRIJEME_DO),
	RADNIK_ID INTEGER NOT NULL CONSTRAINT RADNO_VRIJEME_FK_RADNIK REFERENCES RADNIK(KORISNIK_ID) ON DELETE CASCADE
);

CREATE TABLE REZERVACIJA (
    REZERVACIJA_ID INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT REZERVACIJA_PK PRIMARY KEY,
    POCETAK TIMESTAMP NOT NULL,
    KRAJ TIMESTAMP NOT NULL,
    STATUS STATUS_REZERVACIJE NOT NULL DEFAULT 'AKTIVNA',
    NAPOMENA VARCHAR(500),
	REZERVIRANO_DO TIMESTAMP NULL,
	KLIJENT_ID INTEGER NOT NULL CONSTRAINT REZERVACIJA_FK_KLIJENT REFERENCES KLIJENT(KORISNIK_ID) ON DELETE CASCADE,
    RADNIK_ID  INTEGER NOT NULL CONSTRAINT REZERVACIJA_FK_RADNIK REFERENCES RADNIK(KORISNIK_ID) ON DELETE CASCADE,
    USLUGA_ID  INTEGER NOT NULL CONSTRAINT REZERVACIJA_FK_USLUGA REFERENCES USLUGA(USLUGA_ID) ON DELETE CASCADE
);


CREATE INDEX IF NOT EXISTS IX_REZERVACIJA_RADNIK_POCETAK
    ON REZERVACIJA (RADNIK_ID, POCETAK);
